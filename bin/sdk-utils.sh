#!/usr/bin/env sh
# sdk-utils.sh - Development Utilities for Shebang MCP SDK Consumers
#
# This file contains development-time utilities that consumers can source
# into their own scripts. It is NOT part of the core MCP SDK runtime and
# should NOT be bundled with generated consumer MCP servers.
#
# Utilities:
#   sdk-generate-handler <json-schema> [language]  - Generate handler code from tool schema
#
# Usage:
#   . "${PLUGIN_ROOT}/bin/sdk-utils.sh"
#   sdk-generate-handler '{"name":"my_tool",...}' bash
#
# Or source directly:
#   . <(sdk-generate-handler '{"name":"my_tool",...}')

set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PLUGIN_ROOT="${PLUGIN_ROOT:-$(cd "${SCRIPT_DIR}/.." && pwd)}"
export PLUGIN_ROOT

# Source core SDK for JSON helpers
if [ -f "${PLUGIN_ROOT}/bin/mcp-sdk.sh" ]; then
    . "${PLUGIN_ROOT}/bin/mcp-sdk.sh"
fi

# ============================================================================
# SDK-GENERATE-HANDLER: Language-agnostic code generation for MCP consumers
# ============================================================================
# Takes a tool schema (JSON string) and emits Bash handler code for
# handle_list_tools and handle_tools_call that consumers can source into
# their own scripts.
#
# Usage:
#   sdk-generate-handler '<json-schema>' [language]
#   language: bash (default) | pwsh
#
# Example schema:
#   {"name":"my_tool","description":"Does something","parameters":[{"name":"input","type":"string","required":true}]}

sdk_generate_handler() {
    _sgh_schema="${1:-}"
    _sgh_lang="${2:-bash}"

    if [ -z "${_sgh_schema}" ]; then
        echo "Error: sdk-generate-handler requires a JSON schema argument" >&2
        return 1
    fi

    # Validate schema is valid JSON
    if ! printf '%s' "${_sgh_schema}" | jq -e . >/dev/null 2>&1; then
        echo "Error: Invalid JSON schema provided" >&2
        return 1
    fi

    # Extract tool info from schema
    _sgh_tool_name=$(printf '%s' "${_sgh_schema}" | jq -r '.name // "my_tool"')
    _sgh_tool_desc=$(printf '%s' "${_sgh_schema}" | jq -r '.description // "MCP tool"')
    _sgh_param_count=$(printf '%s' "${_sgh_schema}" | jq -r '.parameters | length // 0')

    # Build parameter declarations for jq argument extraction
    _sgh_param_extract=""
    _sgh_idx=0
    while [ "${_sgh_idx}" -lt "${_sgh_param_count}" ]; do
        _sgh_pname=$(printf '%s' "${_sgh_schema}" | jq -r ".parameters[${_sgh_idx}].name")
        if [ "${_sgh_idx}" -gt 0 ]; then
            _sgh_param_extract="${_sgh_param_extract}
    _sgh_p_${_sgh_pname}=\$(printf '%s' "\${_sgh_args}" | jq -r '.${_sgh_pname} // ""')"
        else
            _sgh_param_extract="    _sgh_p_${_sgh_pname}=\$(printf '%s' "\${_sgh_args}" | jq -r '.${_sgh_pname} // ""')"
        fi
        _sgh_idx=$((_sgh_idx + 1))
    done

    # Bash handler output (default)
    cat << BASH_EOF
# =============================================================================
# Auto-generated MCP Tool Handler: ${_sgh_tool_name}
# Generated by sdk-generate-handler from tool schema
# Source this file in your consumer script:
#   . <(sdk-generate-handler '{"name":"my_tool",...}')
# =============================================================================

handle_list_tools() {
    local id="\${1}"
    local params="\${2:-\"{}\"}"

    local result
    result=\$(jq -cn \\
        --arg name "${_sgh_tool_name}" \\
        --arg desc "${_sgh_tool_desc}" \\
        '{tools:[{name:\$name,description:\$desc,inputSchema:{type:"object",properties:{},required:[]}}]}')

    json_response "\${id}" "\${result}"
}

handle_tools_call() {
    local id="\${1}"
    local params="\${2:-\"{}\"}"
    _sgh_args=\$(printf '%s' "\${params}" | jq -r '.arguments // {}')
${_sgh_param_extract}

    if [ "\${_sgh_tool_name}" = "\$(printf '%s' "\${params}" | jq -r '.name // ""')" ]; then
        # TODO: Implement tool logic here
        # Access arguments via: _sgh_p_input
        local result
        result=\$(jq -cn --arg text "Tool ${_sgh_tool_name} executed successfully" \
            '{content:[{type:"text",text:\$text}],isError:false}')
        json_response "\${id}" "\${result}"
        return 0
    fi

    local err
    err=\$(mcp_error -32601 "Tool not found: \$(printf '%s' "\${params}" | jq -r '.name // ""')")
    json_response "\${id}" "" "\${err}"
}
BASH_EOF
}

# Alias for kebab-case consistency
sdk-generate-handler() {
    sdk_generate_handler "$@"
}
